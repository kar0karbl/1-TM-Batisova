import numpy as np
import matplotlib.pyplot as plt

Tc = 300.0
Tn = 280.0
ap0 = 5e-4
bp = 5e-8
am0 = 30.0
bm = 300.0
k = -1e-3

Tc_eff = (am0 * k * Tn - ap0 * bm * Tc) / (am0 * k - ap0 * bm)
Tn_eff = (ap0 * k * Tc - am0 * bp * Tn) / (ap0 * k - am0 * bp)
print(f"Сдвиг: Tc = {Tc_eff:.1f} K, Tn = {Tn_eff:.1f} K")

D = bp * bm - k**2
T_arr = np.linspace(0, 350, 500)
P_arr, M_arr = [], []

for T in T_arr:              #цикл по температуре
    ap = ap0 * (T - Tc)
    am = am0 * (T - Tn)

    phases = [] # (P, M, Energy)

    #1.ПФ
    if ap > 0 and am > 0:
        phases.append((0, 0, 0))

    #2.СЭ
    if ap < 0:
        P2 = -ap / bp
        if (am + k * P2) > 0:
            E = 0.5 * ap * P2 + 0.25 * bp * P2**2
            phases.append((np.sqrt(P2), 0, E))

    #3.МФ
    if am < 0:
        M2 = -am / bm
        if (ap + k * M2) > 0:
            E = 0.5 * am * M2 + 0.25 * bm * M2**2
            phases.append((0, np.sqrt(M2), E))

    #4.МФФ
    P2_mf = (-ap * bm + am * k) / D
    M2_mf = (-am * bp + ap * k) / D
    if P2_mf > 0 and M2_mf > 0:
        E = (0.5 * ap * P2_mf + 0.25 * bp * P2_mf**2 +
             0.5 * am * M2_mf + 0.25 * bm * M2_mf**2 +
             0.5 * k * P2_mf * M2_mf)
        phases.append((np.sqrt(P2_mf), np.sqrt(M2_mf), E))

    #выбор фазы с минимальной энергией
    if len(phases) > 0:
        best = phases[0]
        for p in phases:
            if p[2] < best[2]:
                best = p
        P_arr.append(best[0])
        M_arr.append(best[1])

P_uC = np.array(P_arr) / 3000   # Перевод P в мкКл/см2

#график
fig, ax1 = plt.subplots(figsize=(10, 5))
ax1.plot(T_arr, P_uC, 'r-', linewidth=2, label='P(T)')
ax1.set_xlabel('T, К')
ax1.set_ylabel('P, мкКл/см²', color='r')
ax1.tick_params(axis='y', labelcolor='r')

ax1_twin = ax1.twinx()
ax1_twin.plot(T_arr, M_arr, 'b-', linewidth=2, label='M(T)')
ax1_twin.set_ylabel('M, Гс', color='b')
ax1_twin.tick_params(axis='y', labelcolor='b')

ax1.axvline(Tc, color='red', linestyle='--', alpha=0.5, label='Tc')
ax1.axvline(Tn, color='blue', linestyle='--', alpha=0.5, label='Tn')
ax1.axvline(Tc_eff, color='red', linestyle=':', label='Tc_эфф')
ax1.axvline(Tn_eff, color='blue', linestyle=':', label='Tn_эфф')

ax1.set_title('Температурные зависимости P(T) и M(T)')
ax1.grid(True, alpha=0.3)
ax1.legend(loc='center left')
plt.tight_layout()
plt.show()

import numpy as np
import matplotlib.pyplot as plt

Tc = 300.0
Tn = 280.0
ap0 = 5e-4
bp = 5e-8
am0 = 30.0
bm = 300.0
k = -1e-3

Tc_eff = (am0 * k * Tn - ap0 * bm * Tc) / (am0 * k - ap0 * bm)
Tn_eff = (ap0 * k * Tc - am0 * bp * Tn) / (ap0 * k - am0 * bp)
print(f"Сдвиг: Tc = {Tc_eff:.1f} K, Tn = {Tn_eff:.1f} K")

D = bp * bm - k**2
T_arr = np.linspace(0, 350, 1000)
P_arr, M_arr = [], []
#массивы для восприимчивостей
chi_e_arr, chi_m_arr = [], []

for T in T_arr:
    ap = ap0 * (T - Tc)
    am = am0 * (T - Tn)

    #(P, M, Energy, chi_e, chi_m)
    phases = []

    #1.ПФ
    if ap > 0 and am > 0:
        ce = 1 / ap if abs(ap) > 1e-5 else 0
        cm = 1 / am if abs(am) > 1e-5 else 0
        phases.append((0, 0, 0, ce, cm))

    #2.СЭ
    if ap < 0:
        P2 = -ap / bp
        H11 = -2 * ap
        H22 = am + k * P2
        if H11 > 0 and H11 * H22 > 0:
            E = 0.5 * ap * P2 + 0.25 * bp * P2**2
            ce = 1 / H11
            cm = 1 / H22 if abs(H22) > 1e-5 else 0
            phases.append((np.sqrt(P2), 0, E, ce, cm))

    #3.МФ
    if am < 0:
        M2 = -am / bm
        H11 = ap + k * M2
        H22 = -2 * am
        if H22 > 0 and H11 * H22 > 0:
            E = 0.5 * am * M2 + 0.25 * bm * M2**2
            ce = 1 / H11 if abs(H11) > 1e-5 else 0
            cm = 1 / H22
            phases.append((0, np.sqrt(M2), E, ce, cm))

    #4.МФФ
    P2_mf = (-ap * bm + am * k) / D
    M2_mf = (-am * bp + ap * k) / D
    if P2_mf > 0 and M2_mf > 0:
        H11 = ap + 3 * bp * P2_mf + k * M2_mf
        H22 = am + 3 * bm * M2_mf + k * P2_mf
        H12 = 2 * k * np.sqrt(P2_mf * M2_mf)
        detH = H11 * H22 - H12**2

        if H11 > 0 and detH > 0:
            E = (0.5 * ap * P2_mf + 0.25 * bp * P2_mf**2 +
                 0.5 * am * M2_mf + 0.25 * bm * M2_mf**2 +
                 0.5 * k * P2_mf * M2_mf)
            ce = H22 / detH if abs(detH) > 1e-10 else 0
            cm = H11 / detH if abs(detH) > 1e-10 else 0
            phases.append((np.sqrt(P2_mf), np.sqrt(M2_mf), E, ce, cm))

    if len(phases) > 0:
        best = phases[0]
        for p in phases:
            if p[2] < best[2]:
                best = p
        P_arr.append(best[0])
        M_arr.append(best[1])
        chi_e_arr.append(best[3])
        chi_m_arr.append(best[4])

P_uC = np.array(P_arr) / 3000
chi_e = np.array(chi_e_arr)
chi_m = np.array(chi_m_arr)

#графики восприимчивостей
fig, ax2 = plt.subplots(figsize=(10, 5))
ax2.plot(T_arr, chi_e, 'g-', linewidth=2, label='χ_e')
ax2.plot(T_arr, chi_m, 'm-', linewidth=2, label='χ_m')

ax2.set_xlabel('T, К')
ax2.set_ylabel('Восприимчивость')
ax2.set_yscale('log')
ax2.set_ylim(1e-3, 1e4)

ax2.axvline(Tc_eff, color='gray', linestyle=':', label=f'Tc_эфф={Tc_eff:.1f} K')
ax2.axvline(Tn_eff, color='black', linestyle='--', label=f'Tn_фф={Tn_eff:.1f} K')

ax2.set_title('Температурные зависимости восприимчивостей')
ax2.grid(True, alpha=0.3, which="both")
ax2.legend()
plt.tight_layout()
plt.show()