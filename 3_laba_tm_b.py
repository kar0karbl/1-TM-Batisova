import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_bvp

# Константы
A = 2.0e-11
K = 4.0e4
Ms = 1.7e6
mu0 = 4 * np.pi * 1e-7

H_K = 2 * K / (mu0 * Ms)
print(f"Поле анизотропии H_K ={H_K/1000:.1f}кА/м")

d0 = np.sqrt(A / K)
delta0 = np.pi * d0

x_nm = np.linspace(-5 * delta0 * 1e9, 5 * delta0 * 1e9, 300)
x_m = x_nm * 1e-9

def solve_wall(H):
    th0 = np.arcsin(H / H_K) if H < H_K else np.pi/2

    def ode(x, y):
        return np.vstack((y[1], (K/A)*np.sin(y[0])*np.cos(y[0]) - (mu0*Ms/(2*A))*H*np.cos(y[0])))

    def bc(ya, yb):
        return np.array([ya[0] - th0, yb[0] - (np.pi - th0)])

    y_guess = np.zeros((2, len(x_m)))
    y_guess[0] = th0 + (np.pi - 2*th0) * (1 / (1 + np.exp(-x_m / d0)))

    return solve_bvp(ode, bc, x_m, y_guess)

print(" ЗАДАНИЕ 1")
sol0 = solve_wall(0)
th0_res = sol0.sol(x_m)[0]
Mz0 = np.cos(th0_res)
Mx0 = np.sin(th0_res)
th_an = 2 * np.arctan(np.exp(x_m / d0))

# Ширина
x9 = np.interp(np.arccos(0.9), th0_res, x_nm)
x1 = np.interp(np.arccos(0.1), th0_res, x_nm)
w_num = abs(x1 - x9)

print(f"Аналитическая ширина: {delta0*1e9:.2f}нм")
print(f"Численная ширина: {w_num:.2f}нм")

fig1, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 5))
fig1.suptitle("Задание 1: Граница без поля", fontsize=14)

ax1.plot(x_nm, th0_res / np.pi, 'b-', lw=2, label='Численное')
ax1.plot(x_nm, th_an / np.pi, 'r--', lw=2, label='Аналитика')
ax1.axhline(0.1, color='gray', ls=':', label='Уровни 0.1 и 0.9')
ax1.axhline(0.9, color='gray', ls=':')
ax1.set_xlabel('x, нм')
ax1.set_ylabel(r'θ/π')
ax1.set_title(r'θ(х) без поля')
ax1.grid(True, ls='--', alpha=0.7)
ax1.legend()

ax2.plot(x_nm, Mz0, 'g-', lw=2, label=r'M_z/M_s = cosθ')
ax2.plot(x_nm, Mx0, 'm--', lw=2, label=r'M_x/M_s = sinθ')
ax2.set_xlabel('x, нм')
ax2.set_ylabel(r'M_i/M_s')
ax2.set_title('Компоненты намагниченности')
ax2.grid(True, ls='--', alpha=0.7)
ax2.legend()
plt.tight_layout()
plt.show()


print("ЗАДАНИЕ 2")
fields = [0, 0.05*H_K, 0.1*H_K, 0.2*H_K]
lbls = ['H = 0','0.05 H_K','0.1 H_K','0.2 H_K']
clrs = ['k','b','g','r']

fig2, (ax3, ax4) = plt.subplots(1, 2, figsize=(15, 5))
fig2.suptitle("Задание 2: Деформация в поле", fontsize=14)

for i, H in enumerate(fields):
    sol = solve_wall(H)
    th = sol.sol(x_m)[0]

    ax3.plot(x_nm, th / np.pi, color=clrs[i], lw=2, label=lbls[i])
    ax4.plot(x_nm, np.cos(th), color=clrs[i], lw=2, label=lbls[i])

ax3.set_xlabel('x, нм')
ax3.set_ylabel(r'θ/π')
ax3.set_title(r'Профиль θ(х)')
ax3.grid(True, ls='--', alpha=0.7)
ax3.legend()

ax4.set_xlabel('x, нм')
ax4.set_ylabel(r'M_z/M_s')
ax4.set_title('Продольная намагниченность')
ax4.grid(True, ls='--', alpha=0.7)
ax4.legend()
plt.tight_layout()
plt.show()

print("Проверка центра:")
for i, H in enumerate(fields):
    sol = solve_wall(H)
    th = sol.sol(x_m)[0]
    idx = np.argmin(np.abs(th - np.pi/2))
    print(f"{lbls[i]:>8}: x = {x_nm[idx]:.2f} нм")


print("ЗАДАНИЕ 3")
def get_w(sol):
    max_slope = np.max(np.abs(sol.sol(x_m)[1]))
    return np.pi / max_slope

h_arr = np.linspace(0, 0.25, 25)
w0_max = get_w(solve_wall(0))

w_list = [get_w(solve_wall(h * H_K)) for h in h_arr]
w_rel = np.array(w_list) / w0_max

plt.figure(figsize=(8, 5))
plt.plot(h_arr, w_rel, 'bo-', lw=2, label='Численный')
plt.plot(h_arr, 1/(1 - h_arr), 'r--', lw=2, label='Теория (1/(1 - H_⊥/H_K))')

plt.xlabel(r'(H_⊥/H_K)')
plt.ylabel(r'(δ/δ_0)')
plt.title('Ширина границы от поперечного поля')
plt.grid(True, ls='--', alpha=0.7)
plt.legend()
plt.tight_layout()
plt.show()